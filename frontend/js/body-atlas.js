    const [ax, ay] = a, [bx, by] = b;
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    const nx = -dy / len, ny = dx / len;
    bow = bow || 0;
    const at = (t, o) => {
      const s = o + bow * Math.sin(Math.PI * t);
      return [ax + dx * t + nx * s, ay + dy * t + ny * s];
    };
    return [at(0, 0), at(0.22, w0 / 2), at(0.5, wm / 2), at(0.78, w1 / 2),
            at(1, 0), at(0.78, -w1 / 2), at(0.5, -wm / 2), at(0.22, -w0 / 2)];
