/* body-atlas.js — the anatomical figure behind the Pulse body map.

   Replaces the old 19-circle stick figure with a real body you can turn round
   and look inside: two views (anterior / posterior) × two layers (muscle /
   skeleton), ~90 individually clickable muscles and ~40 bones.

   HOW THE GEOMETRY WORKS — worth reading before editing coordinates.

   Everything is authored on a 300×720 canvas with the midline at x=150, and
   only the CANVAS-LEFT half of each paired structure is written down. The
   right side is generated by mirroring about the midline. That is not just
   less typing: it makes the figure symmetric *by construction*, so a nudge to
   the left quad can't silently leave the right one behind.

   Side naming is the subtle part. In an ANTERIOR view you face the body, so
   canvas-left is the body's RIGHT side; in a POSTERIOR view you're behind it,
   so canvas-left is its LEFT. Each view therefore declares which key prefix
   the canvas-left half carries (`nearSide`). Get this wrong and a pain logged
   on your right shoulder from the front shows up on your left from the back —
   the same node rendered on the wrong side of the screen. It is the one bug in
   here that would look like a rendering glitch and actually be a data lie.

   The body outline and the muscles are both built from ONE set of landmarks
   (`L` below) — shoulder, elbow, wrist, hip, knee, ankle. The first draft kept
   two independent coordinate sets and they drifted: biceps floating outside a
   silhouette arm that hung somewhere else entirely. Limbs are now capsules
   (`tube`) down those axes and muscles are placed along the same axes, so a
   limb and the muscles in it move together or not at all.

   Shapes are closed point loops fed through a Catmull-Rom smoother. Fusiform
   muscles (biceps, hamstrings, calves) come from `spindle()` — an axis plus
   three widths, giving a tapered belly with tendon points at each end — and
   are smoothed hard. Sheet muscles (pecs, lats, traps, glutes) are explicit
   outlines smoothed gently, so they stay panel-shaped instead of ballooning
   into ellipses.

   Region keys are stable strings; the backend stores whatever it's given
   (`PUT /api/pulse/fitness/body/{region}`), so adding muscles needed no schema
   change. LEGACY maps the old 19 keys onto their nearest new region, so pain
   logged before this rewrite still lights up. */
