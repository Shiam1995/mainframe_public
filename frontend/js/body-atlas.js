  /* Closed Catmull-Rom → cubic bezier. `t` is tension: 1 rounds a sparse loop
     into an organic belly, ~0.5 keeps a sheet's corners. */
  function smooth(pts, t) {
    t = t == null ? 0.6 : t;
    const n = pts.length;
    if (n < 3) return "";
    const f = (v) => Math.round(v * 10) / 10;
    let d = `M${f(pts[0][0])},${f(pts[0][1])}`;
    for (let i = 0; i < n; i++) {
      const p0 = pts[(i - 1 + n) % n], p1 = pts[i], p2 = pts[(i + 1) % n], p3 = pts[(i + 2) % n];
      const c1x = p1[0] + ((p2[0] - p0[0]) / 6) * t, c1y = p1[1] + ((p2[1] - p0[1]) / 6) * t;
      const c2x = p2[0] - ((p3[0] - p1[0]) / 6) * t, c2y = p2[1] - ((p3[1] - p1[1]) / 6) * t;
      d += ` C${f(c1x)},${f(c1y)} ${f(c2x)},${f(c2y)} ${f(p2[0])},${f(p2[1])}`;
    }
    return d + "Z";
  }

  /* Fusiform belly along an axis: widths at 22% / 50% / 78%, plus an optional
     `bow` arcing the whole muscle sideways (biceps bulging off the bone).
     Positive offsets point away from the midline on a downward axis. */
